
from fastapi import APIRouter, Depends, Header, HTTPException, Query
from sqlalchemy.orm import Session
from sqlalchemy import desc

from app.db.database import get_db
from app.db.models import (
    SecurityEvent,
    Alert,
    InvestigationNote,
    AlertActivity
)
from app.schemas import (
    EventIn,
    EventOut,
    AlertOut,
    AlertStatusUpdate,
    InvestigationNoteIn,
    InvestigationNoteOut,
    AlertActivityOut
)
from app.core.config import API_KEY
from app.detection.rules import evaluate_event
from app.detection.correlation import correlate_suspicious_login


router = APIRouter(prefix="/api/v1", tags=["SIEM"])


def require_api_key(x_api_key: str | None):
    if not x_api_key or x_api_key != API_KEY:
        raise HTTPException(
            status_code=401,
            detail="Invalid or missing API key"
        )


def get_alert(db: Session, alert_id: int, tenant_id: str):
    alert = db.query(Alert).filter(
        Alert.id == alert_id,
        Alert.tenant_id == tenant_id
    ).first()

    if not alert:
        raise HTTPException(
            status_code=404,
            detail="Alert not found"
        )

    return alert


# Event Ingestion

@router.post("/ingest", response_model=EventOut, status_code=201)
def ingest_event(
    payload: EventIn,
    x_api_key: str | None = Header(default=None),
    db: Session = Depends(get_db)
):
    require_api_key(x_api_key)

    event = SecurityEvent(**payload.model_dump())
    db.add(event)
    db.flush()

    # Run normal detection rules.
    detections = evaluate_event(event, db)

    # Run event correlation detection.
    correlation_detections = correlate_suspicious_login(event, db)

    # Combine both detection results.
    detections.extend(correlation_detections)

    # Create alerts for all detections.
    for detection in detections:
        alert = Alert(
            tenant_id=event.tenant_id,
            event_id=event.id,
            title=detection.title,
            description=detection.description,
            severity=detection.severity,
            rule_id=detection.rule_id
        )

        db.add(alert)
        db.flush()

        # Record alert creation in activity timeline.
        db.add(AlertActivity(
            tenant_id=alert.tenant_id,
            alert_id=alert.id,
            actor="system",
            action="alert_created",
            details="Alert generated by detection engine."
        ))

    db.commit()
    db.refresh(event)

    return event


# Security Events

@router.get("/events", response_model=list[EventOut])
def list_events(
    tenant_id: str = Query(default="default"),
    limit: int = Query(default=100, ge=1, le=500),
    db: Session = Depends(get_db)
):
    return (
        db.query(SecurityEvent)
        .filter(SecurityEvent.tenant_id == tenant_id)
        .order_by(desc(SecurityEvent.created_at))
        .limit(limit)
        .all()
    )


