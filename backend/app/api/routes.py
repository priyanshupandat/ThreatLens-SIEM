# Alert Acknowledgement

@router.post("/alerts/{alert_id}/acknowledge", response_model=AlertOut)
def acknowledge_alert(
    alert_id: int,
    tenant_id: str = Query(default="default"),
    db: Session = Depends(get_db)
):
    alert = get_alert(db, alert_id, tenant_id)

    if alert.status != "acknowledged":
        old_status = alert.status

        alert.acknowledged = True
        alert.status = "acknowledged"

        db.add(AlertActivity(
            tenant_id=tenant_id,
            alert_id=alert.id,
            actor="local-analyst",
            action="status_changed",
            details=f"Status changed from {old_status} to acknowledged."
        ))

        db.commit()
        db.refresh(alert)

    return alert


# Alert Status Management

@router.post("/alerts/{alert_id}/status", response_model=AlertOut)
def update_alert_status(
    alert_id: int,
    payload: AlertStatusUpdate,
    tenant_id: str = Query(default="default"),
    db: Session = Depends(get_db)
):
    alert = get_alert(db, alert_id, tenant_id)

    old_status = alert.status

    alert.status = payload.status
    alert.acknowledged = payload.status in (
        "acknowledged",
        "resolved"
    )

    if old_status != payload.status:
        db.add(AlertActivity(
            tenant_id=tenant_id,
            alert_id=alert.id,
            actor="local-analyst",
            action="status_changed",
            details=f"Status changed from {old_status} to {payload.status}."
        ))

    db.commit()
    db.refresh(alert)

    return alert


# Investigation Notes

@router.post(
    "/alerts/{alert_id}/notes",
    response_model=InvestigationNoteOut,
    status_code=201
)
def create_investigation_note(
    alert_id: int,
    payload: InvestigationNoteIn,
    tenant_id: str = Query(default="default"),
    db: Session = Depends(get_db)
):
    alert = get_alert(db, alert_id, tenant_id)

    note = InvestigationNote(
        tenant_id=tenant_id,
        alert_id=alert.id,
        analyst=payload.analyst,
        note=payload.note
    )

    db.add(note)

    db.add(AlertActivity(
        tenant_id=tenant_id,
        alert_id=alert.id,
        actor=payload.analyst,
        action="note_added",
        details="Investigation note added."
    ))

    db.commit()
    db.refresh(note)

    return note


@router.get(
    "/alerts/{alert_id}/notes",
    response_model=list[InvestigationNoteOut]
)
def list_investigation_notes(
    alert_id: int,
    tenant_id: str = Query(default="default"),
    db: Session = Depends(get_db)
):
    get_alert(db, alert_id, tenant_id)

    return (
        db.query(InvestigationNote)
        .filter(
            InvestigationNote.alert_id == alert_id,
            InvestigationNote.tenant_id == tenant_id
        )
        .order_by(desc(InvestigationNote.created_at))
        .all()
    )


